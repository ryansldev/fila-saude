/**
 * A linha do contrato para (`de`, `evento`), restrita por `filtro` quando a
 * transição depende da condição (vários destinos para o mesmo evento).
 * `null` = nenhuma linha (transição proibida); mais de uma = contrato ambíguo,
 * erro de programação, lança.
 */
export function singleTransition<S extends string>(
  table: Transition<S>[],
  de: S | "—",
  event: string,
  filter: (t: Transition<S>) => boolean = () => true,
): Transition<S> | null {
  const rows = table.filter((t) => t.de === de && t.event === event && filter(t));
  if (rows.length > 1) throw new Error(`contrato: mais de uma linha para "${de}" com "${event}"`);
  return rows[0] ?? null;
}

/**
 * Destino de `evento` a partir do estado `de`; `null` = transição proibida.
 * Linhas com o mesmo (de, evento) e o mesmo destino devolvem esse destino.
 * Se os destinos divergem (ex.: "Não compareceu" por nº de pulos), é erro de
 * programação: quem depende da condição escolhe a linha na tabela.
 */
export function applyTransition<S extends string>(table: Transition<S>[], de: S, event: string): S | "(mesmo)" | null {
  const rows = table.filter((t) => t.de === de && t.event === event);
  const first = rows[0];
  if (!first) return null;
  if (rows.some((t) => t.for !== first.for)) {
    throw new Error(`transição ambígua: de "${de}" com o evento "${event}" tem mais de um destino`);
  }
  return first.for === "(não cria)" ? null : first.for;
}
