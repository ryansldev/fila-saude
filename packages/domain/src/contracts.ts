// Pendência fica na entrada: com ela o check-in é recusado.
export type ItemState = "remote" | "present" | "called" | "done_in_stage" | "left_queue" | "reassigned";

export type SessionState = "planned" | "open" | "cancelled" | "closed";

export type Transition<S extends string> = {
  de: S | "—";
  /** Parêntese da célula "De" da spec, ex.: "vaga segura", "nunca chamado". */
  qualifier?: string;
  /**
   * Texto da célula "De" quando a spec agrupa estados numa linha só
   * (ex.: "Alocada, Confirmada ou Na fila") ou escreve o estado de outro jeito.
   * Linhas seguidas com o mesmo `textOf` e o resto igual viram uma linha na
   * tabela gerada (scripts/specs-gen.mjs). Sem ele, a célula é o rótulo do
   * estado + "(qualificador)".
   */
  textOf?: string;
  event: string;
  for: S | "(mesmo)" | "(não cria)";
  /** Parêntese da célula "Para" da spec, ex.: "data original", "ou Na fila, se a sessão já abriu". */
  forQualifier?: string;
  condition: string;
  effects: string;
  /** Primeiro ID de regra citado na linha (RN-…, INV-…), ou "". */
  rule: string;
  spec: "lista-espera" | "marcacao" | "excecoes" | "fila-do-dia" | "chamada" | "contingencia";
};

